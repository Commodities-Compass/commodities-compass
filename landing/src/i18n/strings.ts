export function pathFor(locale: Locale, path: string = ''): string {
  const clean = path.replace(/^\//, '');
  if (locale === DEFAULT_LOCALE) return `/${clean}`.replace(/\/$/, '') || '/';
  return `/${locale}/${clean}`.replace(/\/$/, '') || `/${locale}`;
}
